  await download.saveAs(resolve(output,'downloaded-teapot.png'));
  assert.deepEqual(await readFile(resolve(output,'downloaded-teapot.png')),png);
  await done.getByRole('button',{name:'הגדלת התמונה',exact:true}).click();await page.getByRole('dialog').waitFor();await page.keyboard.press('Escape');
