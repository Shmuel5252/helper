  worker=spawn(process.execPath,['scripts/image-worker/worker.mjs'],{cwd:resolve('.'),windowsHide:true,env:{...process.env,IMAGE_APP_URL:base,IMAGE_WORKER_SECRET:'local-image-test-worker-secret-123456789',IMAGE_API_URL:'http://127.0.0.1:7860',IMAGE_LOCAL_DATA_DIR:resolve('.local-images/test-live'),IMAGE_CLOUD_CONSENT:''},stdio:'inherit'});
