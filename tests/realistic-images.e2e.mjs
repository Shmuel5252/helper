  assert.equal((await context.request.post(base+'/api/worker/images',{data:{action:'claim'}})).status(),401);
  assert.equal((await context.request.post(base+'/api/images/jobs',{headers:{Origin:'https://attacker.invalid'},data:{}})).status(),403);
  console.log('PASS authentication, worker secret and cross-origin protection');
  const denied=await context.request.post(base+'/api/images/jobs',{data:{id:crypto.randomUUID(),text:'צור לי תמונה של חתול'}});
  assert.equal(denied.status(),412);
